//! Reference tests for Jubjub, Pallas, and Vesta curve arithmetic.
//!
//! These tests mirror the device-side tests in `src/ffi.rs` but run on the host
//! using the reference implementations from `jubjub` and `pasta_curves`.
//!
//! # Byte-order convention
//!
//! Test vectors use **big-endian** byte order (same as the Ledger SDK in ffi.rs).
//! Internally we convert to the little-endian format expected by the Rust crates.

use ff::PrimeField;
use group::{prime::PrimeCurveAffine, Curve};
use pasta_curves::arithmetic::CurveAffine;
use pasta_curves::{pallas, vesta};

// ---------------------------------------------------------------------------
// Utility helpers
// ---------------------------------------------------------------------------

/// Reverse bytes: big-endian ↔ little-endian.
fn rev(mut b: [u8; 32]) -> [u8; 32] {
    b.reverse();
    b
}

// ---------------------------------------------------------------------------
// Pallas helpers
// ---------------------------------------------------------------------------

/// Create a Pallas projective point from big-endian affine coordinates (x, y).
fn pallas_from_be(x_be: [u8; 32], y_be: [u8; 32]) -> pallas::Point {
    let x = pallas::Base::from_repr(rev(x_be)).unwrap();
    let y = pallas::Base::from_repr(rev(y_be)).unwrap();
    pallas::Affine::from_xy(x, y).unwrap().to_curve()
}

/// Extract big-endian affine (x, y) from a Pallas projective point.
fn pallas_to_be(pt: pallas::Point) -> ([u8; 32], [u8; 32]) {
    let affine = pt.to_affine();
    let coords = affine.coordinates().unwrap();
    (rev(coords.x().to_repr()), rev(coords.y().to_repr()))
}

// ---------------------------------------------------------------------------
// Vesta helpers
// ---------------------------------------------------------------------------

/// Create a Vesta projective point from big-endian affine coordinates (x, y).
fn vesta_from_be(x_be: [u8; 32], y_be: [u8; 32]) -> vesta::Point {
    let x = vesta::Base::from_repr(rev(x_be)).unwrap();
    let y = vesta::Base::from_repr(rev(y_be)).unwrap();
    vesta::Affine::from_xy(x, y).unwrap().to_curve()
}

/// Extract big-endian affine (x, y) from a Vesta projective point.
fn vesta_to_be(pt: vesta::Point) -> ([u8; 32], [u8; 32]) {
    let affine = pt.to_affine();
    let coords = affine.coordinates().unwrap();
    (rev(coords.x().to_repr()), rev(coords.y().to_repr()))
}

// ---------------------------------------------------------------------------
// Jubjub helpers
//
// The Jubjub curve (twisted Edwards) uses (u, v) coordinates. The Ledger SDK
// calls them (x, y): x → u, y → v.
//
// Compressed Edwards encoding: LE(v) with bit 255 = parity of u.
// ---------------------------------------------------------------------------

/// Create a Jubjub extended point from big-endian affine coordinates (u, v).
///
/// `u_be` maps to the Ledger "x", `v_be` maps to the Ledger "y".
fn jubjub_from_be(u_be: [u8; 32], v_be: [u8; 32]) -> jubjub::ExtendedPoint {
    // Convert to LE
    let u_le = rev(u_be);
    let v_le = rev(v_be);

    // Compressed Edwards: LE(v) with bit 255 = parity of u (bit 0 of u_le[0]).
    let u_sign = u_le[0] & 1;
    let mut compressed = v_le;
    compressed[31] |= u_sign << 7;

    let affine = jubjub::AffinePoint::from_bytes(compressed).unwrap();
    jubjub::ExtendedPoint::from(affine)
}

/// Extract big-endian (u, v) from a Jubjub extended point.
///
/// Returns `(u_be, v_be)` mapping to Ledger `(x, y)` respectively.
fn jubjub_to_be(pt: jubjub::ExtendedPoint) -> ([u8; 32], [u8; 32]) {
    let affine = jubjub::AffinePoint::from(pt);
    let u_be = rev(affine.get_u().to_bytes());
    let v_be = rev(affine.get_v().to_bytes());
    (u_be, v_be)
}

