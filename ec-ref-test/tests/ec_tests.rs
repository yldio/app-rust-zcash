// Pallas – point negation (double-negation round-trip)
// Weierstrass negation flips y but keeps x.
// ---------------------------------------------------------------------------

#[test]
fn test_point_neg_pallas() {
    let px: [u8; 32] = [
        0x16, 0xd2, 0xcd, 0xa8, 0xef, 0x80, 0xb4, 0xc4, 0x9b, 0x3a, 0xda, 0xcc, 0x38, 0x4f,
        0xea, 0xf1, 0xfb, 0x38, 0xa3, 0x5b, 0xe1, 0xbc, 0x02, 0xad, 0x6a, 0xa4, 0xc4, 0x99,
        0xb6, 0xc6, 0xfe, 0xe6,
    ];
    let py: [u8; 32] = [
        0x03, 0x88, 0xe7, 0x11, 0xd1, 0x20, 0xf9, 0x03, 0xf0, 0x1c, 0x36, 0xe2, 0x14, 0x39,
        0x21, 0xeb, 0x6b, 0xc2, 0x7f, 0xdd, 0xd5, 0xd3, 0xb6, 0x53, 0x44, 0xc1, 0xa7, 0x67,
        0x3d, 0x7d, 0x0d, 0x78,
    ];

    let p = pallas_from_be(px, py);
    let neg_p = -p;
    let (neg_x, neg_y) = pallas_to_be(neg_p);

    // Weierstrass: x coordinate is preserved under negation.
    assert_eq!(neg_x, px, "Pallas neg: x should be unchanged");
    assert_ne!(neg_y, py, "Pallas neg: y should change");

    // Double-negation must recover the original point.
    let p2 = -neg_p;
    let (back_x, back_y) = pallas_to_be(p2);
    assert_eq!(back_x, px, "Pallas double-neg: wrong x");
    assert_eq!(back_y, py, "Pallas double-neg: wrong y");
}

